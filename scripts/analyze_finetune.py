#!/usr/bin/env python3
"""Analyze a 4_finetune_text matrix run (`runs/finetune_<stamp>/`).

Consumes:
  <matrix_dir>/matrix_summary.json
  <matrix_dir>/<backbone_short>__<mixture>/summary.json  — per cell
Produces (under <matrix_dir>/analysis/):
  matrix_long.csv        one row per (backbone × mixture × test_source) with all metrics
  matrix_report.md       human-readable summary: per-test matrices, best cells, transfer gap
  heatmap_<metric>_<test_source>.png   3×7 heatmaps per test source (matplotlib, soft-dep)

The companion analyzer `analyze_probe.py` handles OpenRouter / local-probe batches
(predictions.jsonl schema). This one is strictly for the finetune matrix format.

Usage:
  python3 scripts/analyze_finetune.py runs/finetune_20261113_162724
  python3 scripts/analyze_finetune.py runs/finetune_20261113_162724 --primary macro_f1_3cls
"""

import argparse
import csv
import json
import sys
from pathlib import Path

# Canonical orderings — matches the ladder structure of each axis.
BACKBONES_ORDER = [
    "xlm-roberta-large",
    "xlm-r-parla",
    "xlm-r-parlasent",
]
MIXTURES_ORDER = ["S", "P", "R", "SP", "SR", "PR", "SPR"]
TEST_SOURCES_ORDER = ["parlasent_sl", "parlaspeech_si", "rog_dia"]
LABELS_3 = ["negative", "neutral", "positive"]

# ParlaSpeech labels were generated by XLM-R-ParlaSent itself, so cells where
# that backbone trains on a mixture containing P are self-labeled.
SELF_LABELED_BACKBONE = "xlm-r-parlasent"


def is_self_labeled(backbone_short: str, mixture: str) -> bool:
    return backbone_short == SELF_LABELED_BACKBONE and "P" in mixture


def backbone_short(backbone: str) -> str:
    return backbone.rsplit("/", 1)[-1]


def load_matrix(matrix_dir: Path) -> tuple[dict, list[dict]]:
    """Return (matrix_meta, cells) where each cell dict has resolved backbone_short,
    mixture, metrics_by_test, and a self_labeled flag. Skips non-completed cells."""
    ms_path = matrix_dir / "matrix_summary.json"
    if not ms_path.exists():
        raise SystemExit(f"matrix_summary.json not found in {matrix_dir}")
    meta = json.loads(ms_path.read_text())
    cells = []
    for cell_entry in meta.get("cells", []):
        if not cell_entry.get("status", "").startswith("ok") and not \
                cell_entry.get("status", "").startswith("degraded"):
            continue
        tag = cell_entry["cell"]
        sp = matrix_dir / tag / "summary.json"
        if not sp.exists():
            continue
        s = json.loads(sp.read_text())
        bb_short = backbone_short(s["config"]["backbone"])
        mix = s["config"]["mixture"]
        cells.append({
            "tag": tag,
            "backbone_short": bb_short,
            "mixture": mix,
            "self_labeled": is_self_labeled(bb_short, mix),
            "status": cell_entry.get("status"),
            "elapsed_sec": cell_entry.get("elapsed_sec"),
            "train_n": s.get("train_n"),
            "dev_n": s.get("dev_n"),
            "test_n_by_src": s.get("test_n_by_src", {}),
            "metrics_by_test": s.get("metrics_by_test", {}),
            "label_norm": s.get("label_norm", {}),
        })
    return meta, cells


# ---------------------------------------------------------------------------
# Long-form CSV
# ---------------------------------------------------------------------------

LONG_CSV_FIELDS = [
    "tag", "backbone_short", "mixture", "self_labeled", "status", "elapsed_sec",
    "train_n", "dev_n", "test_source", "test_n",
    "r2", "spearman", "mae",
    "acc_6cls", "macro_f1_6cls",
    "acc_3cls", "macro_f1_3cls",
    "rec_neg", "rec_neu", "rec_pos",
    "prec_neg", "prec_neu", "prec_pos",
    "minority_positive_recall",
]


def write_long_csv(cells: list[dict], out_path: Path) -> int:
    rows = []
    for c in cells:
        for src in TEST_SOURCES_ORDER:
            m = c["metrics_by_test"].get(src)
            if not m:
                continue
            rec3 = m.get("per_class_recall_3cls") or [None, None, None]
            prc3 = m.get("per_class_precision_3cls") or [None, None, None]
            rows.append({
                "tag": c["tag"],
                "backbone_short": c["backbone_short"],
                "mixture": c["mixture"],
                "self_labeled": int(c["self_labeled"]),
                "status": c["status"],
                "elapsed_sec": c["elapsed_sec"],
                "train_n": c["train_n"],
                "dev_n": c["dev_n"],
                "test_source": src,
                "test_n": m.get("n"),
                "r2": m.get("r2"),
                "spearman": m.get("spearman"),
                "mae": m.get("mae"),
                "acc_6cls": m.get("acc_6cls"),
                "macro_f1_6cls": m.get("macro_f1_6cls"),
                "acc_3cls": m.get("acc_3cls"),
                "macro_f1_3cls": m.get("macro_f1_3cls"),
                "rec_neg": rec3[0],
                "rec_neu": rec3[1],
                "rec_pos": rec3[2],
                "prec_neg": prc3[0],
                "prec_neu": prc3[1],
                "prec_pos": prc3[2],
                "minority_positive_recall": m.get("minority_positive_recall"),
            })
    with open(out_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=LONG_CSV_FIELDS)
        w.writeheader()
        w.writerows(rows)
    return len(rows)


# ---------------------------------------------------------------------------
# Markdown report
# ---------------------------------------------------------------------------

METRIC_DISPLAY = {
    "r2":            "R²",
    "spearman":      "Spearman ρ",
    "mae":           "MAE",
    "macro_f1_6cls": "macro-F1 (6-cls)",
    "macro_f1_3cls": "macro-F1 (3-cls)",
    "acc_6cls":      "acc (6-cls)",
    "acc_3cls":      "acc (3-cls)",
}
HIGHER_IS_BETTER = {"r2", "spearman", "macro_f1_6cls", "macro_f1_3cls", "acc_6cls", "acc_3cls"}


def _matrix_values(cells: list[dict], test_src: str, metric: str) -> dict:
    """Return {(backbone, mixture): value} for a given test source + metric."""
    out = {}
    for c in cells:
        m = c["metrics_by_test"].get(test_src)
        if not m:
            continue
        v = m.get(metric)
        if v is None:
            continue
        out[(c["backbone_short"], c["mixture"])] = v
    return out


def _fmt(v, metric: str) -> str:
    if v is None:
        return "  —   "
    if metric == "mae":
        return f"{v:+.3f}"
    return f"{v:+.3f}"


def render_matrix_table(vals: dict, metric: str, mark_self_labeled: set[tuple[str, str]]) -> str:
    """Render a backbone × mixture table in Markdown."""
    header = "| backbone \\ mixture | " + " | ".join(MIXTURES_ORDER) + " |"
    sep    = "|" + "---|" * (len(MIXTURES_ORDER) + 1)
    lines = [header, sep]
    hib = metric in HIGHER_IS_BETTER
    # Find best per column and per matrix for bolding.
    best_val = max(vals.values()) if (vals and hib) else (min(vals.values()) if vals else None)
    for bb in BACKBONES_ORDER:
        cells = []
        for mix in MIXTURES_ORDER:
            v = vals.get((bb, mix))
            s = _fmt(v, metric)
            if (bb, mix) in mark_self_labeled:
                s = f"⚠ {s}"
            if v is not None and best_val is not None and v == best_val:
                s = f"**{s}**"
            cells.append(s)
        lines.append(f"| `{bb}` | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def best_cells(cells: list[dict], metric: str, exclude_self_labeled: bool = False):
    """Return list of (test_src, backbone, mixture, value) tied for best per test_src."""
    out = []
    hib = metric in HIGHER_IS_BETTER
    for src in TEST_SOURCES_ORDER:
        candidates = []
        for c in cells:
            if exclude_self_labeled and c["self_labeled"]:
                continue
            m = c["metrics_by_test"].get(src)
            if not m:
                continue
            v = m.get(metric)
            if v is None:
                continue
            candidates.append((c["backbone_short"], c["mixture"], v))
        if not candidates:
            out.append((src, None, None, None))
            continue
        best = max(candidates, key=lambda t: t[2]) if hib else min(candidates, key=lambda t: t[2])
        out.append((src, best[0], best[1], best[2]))
    return out


def transfer_gap(cells: list[dict]) -> list[tuple[str, float, float, float]]:
    """For each backbone's S-only cell (trained on ParlaSent-SL only), compute the gap
    between parlasent_sl test and rog_dia test using R². Returns [(backbone, r2_sl, r2_rog, gap)]."""
    rows = []
    for bb in BACKBONES_ORDER:
        c = next((x for x in cells if x["backbone_short"] == bb and x["mixture"] == "S"), None)
        if c is None:
            continue
        sl = (c["metrics_by_test"].get("parlasent_sl") or {}).get("r2")
        rog = (c["metrics_by_test"].get("rog_dia") or {}).get("r2")
        if sl is None or rog is None:
            continue
        rows.append((bb, sl, rog, sl - rog))
    return rows


def write_report(meta: dict, cells: list[dict], out_path: Path,
                 primary_metric: str = "macro_f1_3cls") -> None:
    md_lines: list[str] = []
    md_lines.append(f"# Finetune matrix — {meta.get('ts_start', '?')}")
    md_lines.append("")
    md_lines.append(f"**mode**: `{meta.get('mode')}` · **cells reported**: {len(cells)}")
    ms_missing = meta.get("missing_sources") or []
    if ms_missing:
        md_lines.append(f"**missing sources flagged by matrix**: {', '.join(ms_missing)}")
    md_lines.append("")
    md_lines.append("⚠ marks cells where the chosen backbone trained on data labeled by its own "
                    "predecessor (XLM-R-ParlaSent trained on ParlaSpeech, whose sentiment layer was "
                    "generated by XLM-R-ParlaSent itself). These numbers measure self-consistency, "
                    "not genuine transfer.")
    md_lines.append("")

    mark_self = {(c["backbone_short"], c["mixture"]) for c in cells if c["self_labeled"]}

    # Per-metric per-test-source matrices.
    for metric in ("r2", "spearman", "macro_f1_3cls", "macro_f1_6cls", "mae"):
        md_lines.append(f"## {METRIC_DISPLAY[metric]}")
        md_lines.append("")
        for src in TEST_SOURCES_ORDER:
            vals = _matrix_values(cells, src, metric)
            if not vals:
                continue
            md_lines.append(f"### Test: `{src}`")
            md_lines.append("")
            md_lines.append(render_matrix_table(vals, metric, mark_self))
            md_lines.append("")

    # Best-cell summaries.
    md_lines.append(f"## Best cells (by {METRIC_DISPLAY[primary_metric]})")
    md_lines.append("")
    for include_self, label in ((True, "All cells"), (False, "Self-labeled cells excluded")):
        md_lines.append(f"### {label}")
        md_lines.append("")
        md_lines.append("| test source | backbone | mixture | value |")
        md_lines.append("|---|---|---|---|")
        for src, bb, mix, v in best_cells(cells, primary_metric,
                                          exclude_self_labeled=not include_self):
            if bb is None:
                md_lines.append(f"| `{src}` | — | — | — |")
            else:
                md_lines.append(f"| `{src}` | `{bb}` | `{mix}` | {v:+.3f} |")
        md_lines.append("")

    # Parliament → dialogue transfer gap.
    gap = transfer_gap(cells)
    if gap:
        md_lines.append("## Parliament → dialogue R² gap (S-only cells)")
        md_lines.append("")
        md_lines.append("Trained on ParlaSent-SL alone; delta between parlasent_sl test and rog_dia test.")
        md_lines.append("")
        md_lines.append("| backbone | R² @ parlasent_sl | R² @ rog_dia | Δ |")
        md_lines.append("|---|---|---|---|")
        for bb, sl, rog, d in gap:
            md_lines.append(f"| `{bb}` | {sl:+.3f} | {rog:+.3f} | {d:+.3f} |")
        md_lines.append("")

    # Degenerate (collapse) cells — flagged when a 3-class recall vector is near-one-hot.
    degenerate = []
    for c in cells:
        for src, m in c["metrics_by_test"].items():
            rec3 = m.get("per_class_recall_3cls")
            if not rec3:
                continue
            if max(rec3) >= 0.99 and sum(rec3) <= max(rec3) + 0.02:
                collapsed = LABELS_3[rec3.index(max(rec3))]
                degenerate.append((c["tag"], src, collapsed, m.get("macro_f1_3cls")))
    if degenerate:
        md_lines.append("## Degenerate cells (3-cls recall collapsed onto one class)")
        md_lines.append("")
        md_lines.append("| cell | test | collapsed onto | F1_3cls |")
        md_lines.append("|---|---|---|---|")
        for tag, src, col, f1 in degenerate:
            md_lines.append(f"| `{tag}` | `{src}` | {col} | {f1:+.3f} |")
        md_lines.append("")

    out_path.write_text("\n".join(md_lines))


# ---------------------------------------------------------------------------
# Heatmaps (matplotlib soft-dep)
# ---------------------------------------------------------------------------

def write_heatmaps(cells: list[dict], out_dir: Path, metric: str) -> list[Path]:
    try:
        import numpy as np
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("  [skip heatmaps] matplotlib / numpy not installed")
        return []

    written = []
    hib = metric in HIGHER_IS_BETTER
    cmap = "viridis" if hib else "viridis_r"

    for src in TEST_SOURCES_ORDER:
        vals = _matrix_values(cells, src, metric)
        if not vals:
            continue
        arr = np.full((len(BACKBONES_ORDER), len(MIXTURES_ORDER)), np.nan)
        for i, bb in enumerate(BACKBONES_ORDER):
            for j, mix in enumerate(MIXTURES_ORDER):
                v = vals.get((bb, mix))
                if v is not None:
                    arr[i, j] = v

        fig, ax = plt.subplots(figsize=(1.0 * len(MIXTURES_ORDER) + 1.8, 2.4))
        im = ax.imshow(arr, aspect="auto", cmap=cmap)
        ax.set_xticks(range(len(MIXTURES_ORDER)))
        ax.set_xticklabels(MIXTURES_ORDER)
        ax.set_yticks(range(len(BACKBONES_ORDER)))
        ax.set_yticklabels(BACKBONES_ORDER)
        for i in range(arr.shape[0]):
            for j in range(arr.shape[1]):
                v = arr[i, j]
                if np.isnan(v):
                    continue
                ax.text(j, i, f"{v:+.2f}", ha="center", va="center",
                        fontsize=8, color="white" if hib else "black")
                if is_self_labeled(BACKBONES_ORDER[i], MIXTURES_ORDER[j]):
                    ax.text(j - 0.35, i - 0.3, "⚠", ha="center", va="center",
                            fontsize=9, color="red")
        ax.set_title(f"{METRIC_DISPLAY[metric]}  —  test: {src}", fontsize=10)
        fig.colorbar(im, ax=ax, fraction=0.025, pad=0.02)
        fig.tight_layout()
        path = out_dir / f"heatmap_{metric}_{src}.png"
        fig.savefig(path, dpi=150)
        plt.close(fig)
        written.append(path)
    return written


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("matrix_dir", type=Path, help="runs/finetune_<stamp>/")
    p.add_argument("--primary", default="macro_f1_3cls",
                   choices=sorted(METRIC_DISPLAY.keys()),
                   help="metric to rank best-cells by (default: macro_f1_3cls)")
    p.add_argument("--no-heatmaps", action="store_true")
    args = p.parse_args()

    md = args.matrix_dir
    if not md.exists():
        raise SystemExit(f"no such dir: {md}")

    out_dir = md / "analysis"
    out_dir.mkdir(exist_ok=True)

    meta, cells = load_matrix(md)
    print(f"Loaded {len(cells)} cells from {md}")

    csv_path = out_dir / "matrix_long.csv"
    n_rows = write_long_csv(cells, csv_path)
    print(f"  wrote {csv_path}  ({n_rows} rows)")

    report_path = out_dir / "matrix_report.md"
    write_report(meta, cells, report_path, primary_metric=args.primary)
    print(f"  wrote {report_path}")

    if not args.no_heatmaps:
        for metric in ("r2", "spearman", "macro_f1_3cls"):
            written = write_heatmaps(cells, out_dir, metric)
            for w in written:
                print(f"  wrote {w}")


if __name__ == "__main__":
    main()
